import { CategoryId, Difficulty, Question } from '../src/types';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packsDir = path.resolve(__dirname, '../src/data/packs');

if (!fs.existsSync(packsDir)) {
  fs.mkdirSync(packsDir, { recursive: true });
}

console.log('--- GEOGRAFIST Question Pack Compiler & Generator ---');

// 1. Generate all deterministic variants
const templateReport = generateQuestionVariantsFromFacts();
console.log(`Derived ${templateReport.generatedVariantsCount} variants from ${templateReport.sourceFactsCount} primary facts.`);

// 2. Validate all seed and derived questions
const allCombined: Question[] = [
  ...flagQuestions,
  ...capitalQuestions,
  ...historyQuestions,
  ...currentAffairsQuestions,
  ...explorerQuestions,
  ...verifiedExpansionQuestions,
  ...templateReport.variants,
];

console.log(`Total candidate questions across all sources: ${allCombined.length}`);

// Deduplicate and validate
const seenIds = new Set<string>();
const validQuestions: Question[] = [];
let rejectedDuplicates = 0;
let rejectedSchema = 0;

for (const q of allCombined) {
  if (seenIds.has(q.id)) {
    rejectedDuplicates++;
    continue;
  }
  seenIds.add(q.id);

  const val = validateQuestion(q);
  if (!val.valid) {
    console.warn(`Schema rejection for ${q.id}: ${val.error}`);
    rejectedSchema++;
    continue;
  }

  validQuestions.push(q);
}

console.log(`Valid verified questions after validation: ${validQuestions.length}`);
console.log(`Rejected: ${rejectedDuplicates} duplicate IDs, ${rejectedSchema} schema violations`);

// 3. Partition by category
